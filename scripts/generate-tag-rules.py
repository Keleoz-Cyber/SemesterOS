"""Keep the offline mobile vocabulary identical to the backend vocabulary."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'services/api/app/data/tag_rules.json'
TARGET = ROOT / 'apps/mobile/lib/features/tags/tag_rules.g.dart'

def generate():
    rules = json.loads(SOURCE.read_text(encoding='utf-8'))
    source = json.dumps(rules, ensure_ascii=False, separators=(',', ':'))
    TARGET.write_text('// Generated by scripts/generate-tag-rules.py.\n'
        '// Classification runs on-device without a model or network request.\n'
        "const tagRuleJson = r'''" + source + "''';\n", encoding='utf-8')

if __name__ == '__main__':
    generate()
